"""Refresh public brand thumbnails. Requires Python 3 + Pillow; not part of the build.
Uses the existing public Supabase configuration. Never writes credentials or source URLs.
"""
import concurrent.futures
import io
import json
import os
import re
import urllib.parse
import urllib.request
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
config = dict(os.environ)
for filename in ('.env', '.env.local'):
    path = root / filename
    if path.exists():
        for line in path.read_text().splitlines():
            if '=' in line and not line.strip().startswith('#'):
                key, value = line.split('=', 1)
                config.setdefault(key.strip(), value.strip().strip('"').strip("'"))
base = config.get('VITE_SUPABASE_URL', '').rstrip('/')
key = config.get('VITE_SUPABASE_ANON_KEY', '')
if not base or not key:
    raise SystemExit('Missing public Supabase configuration.')
request = urllib.request.Request(base + '/rest/v1/brands?select=id,url_image&is_active=eq.true', headers={'apikey': key, 'Authorization': 'Bearer ' + key})
with urllib.request.urlopen(request, timeout=15) as response:
    brands = json.load(response)
out = root / 'public/images/brands'
out.mkdir(exist_ok=True)

def optimize(brand):
    source = brand.get('url_image') or ''
    identifier = brand['id']
    if not re.fullmatch(r'[A-Za-z0-9_-]{1,80}', identifier): return None
    url = urllib.parse.urlparse(source)
    if url.scheme != 'https' or url.hostname != urllib.parse.urlparse(base).hostname: return None
    try:
        with urllib.request.urlopen(source, timeout=15) as response:
            content = response.read(10 * 1024 * 1024 + 1)
        if len(content) > 10 * 1024 * 1024: return None
        image = Image.open(io.BytesIO(content)).convert('RGBA')
        image.thumbnail((160, 160))
        image.save(out / (identifier + '.webp'), quality=86, method=6)
        fingerprint = 5381
        for character in source:
            fingerprint = ((fingerprint * 33) ^ ord(character)) & 0xffffffff
        return identifier, {'fingerprint': fingerprint, 'file': '/images/brands/' + identifier + '.webp'}
    except Exception:
        return None
with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    results = [result for result in pool.map(optimize, brands) if result]
manifest = dict(sorted(results))
(root / 'lib/brand-images.ts').write_text('// Generated by scripts/optimize-brand-images.py. Source URLs are not stored.\nexport const brandImages: Record<string, { fingerprint: number; file: string }> = ' + json.dumps(manifest, indent=2) + ';\n')
print(f'Optimized {len(results)} brand images; other images keep their live fallback.')
